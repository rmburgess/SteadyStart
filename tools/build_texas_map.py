"""Build js/texas-map.js: Texas Health Service Regions as SVG paths.

Inputs (not stored in the repo):
  1. counties-10m.json from the us-atlas npm package (U.S. Census Bureau
     cartographic boundaries, public domain):
     https://cdn.jsdelivr.net/npm/us-atlas@3.0.1/counties-10m.json
  2. The county -> region table on the Texas DSHS page
     "Texas County Numbers and Public Health Regions":
     https://www.dshs.texas.gov/center-health-statistics/texas-county-numbers-public-health-regions
     saved as HTML.

Usage:
  python3 tools/build_texas_map.py counties-10m.json phr.html > js/texas-map.js

The site itself never loads either file; it only uses the generated paths.
"""
import html
import json
import math
import re
import sys

W = 500.0  # viewBox width


def region_table(path):
    s = open(path, encoding="utf-8", errors="ignore").read()
    table = {}
    for row in re.findall(r"<tr[^>]*>(.*?)</tr>", s, re.S):
        cells = [html.unescape(re.sub(r"<[^>]+>", "", c)).strip()
                 for c in re.findall(r"<t[dh][^>]*>(.*?)</t[dh]>", row, re.S)]
        if len(cells) >= 5 and cells[2].startswith("48"):
            table[cells[2]] = cells[4]  # FIPS -> Health Service Region, e.g. "4/5N"
    return table


def main(topo_path, phr_path):
    topo = json.load(open(topo_path))
    regions = region_table(phr_path)
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]

    # Decode delta-encoded, quantized arcs to lon/lat.
    arcs = []
    for arc in topo["arcs"]:
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx
            y += dy
            pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)

    counties = [g for g in topo["objects"]["counties"]["geometries"]
                if g["id"].startswith("48")]
    missing = [g["id"] for g in counties if g["id"] not in regions]
    if missing or len(counties) != 254:
        sys.exit("county/region mismatch: %d counties, missing %s" % (len(counties), missing))

    def rings(g):
        polys = g["arcs"] if g["type"] == "MultiPolygon" else [g["arcs"]]
        for poly in polys:
            for ring in poly:
                yield ring

    # Simple projection: equirectangular scaled by cos(latitude) at Texas' middle.
    lons = [p[0] for g in counties for r in rings(g) for i in r for p in arcs[i if i >= 0 else ~i]]
    lats = [p[1] for g in counties for r in rings(g) for i in r for p in arcs[i if i >= 0 else ~i]]
    k = math.cos(math.radians((min(lats) + max(lats)) / 2))
    x0, x1 = min(lons) * k, max(lons) * k
    scale = W / (x1 - x0)
    H = (max(lats) - min(lats)) * scale

    def proj(p):
        return ((p[0] * k - x0) * scale, (max(lats) - p[1]) * scale)

    def ring_path(ring):
        pts = []
        for i in ring:
            seg = arcs[i] if i >= 0 else list(reversed(arcs[~i]))
            pts.extend(seg if not pts else seg[1:])
        out, last = [], None
        for p in pts:
            q = "%.1f,%.1f" % proj(p)
            if q != last:
                out.append(q)
                last = q
        return "M" + "L".join(out) + "Z"

    # Fill shapes per region, and which arcs separate regions (or face outside).
    paths, arc_owners, sums = {}, {}, {}
    for g in counties:
        code = regions[g["id"]]
        for ring in rings(g):
            paths.setdefault(code, []).append(ring_path(ring))
            for i in ring:
                arc_owners.setdefault(i if i >= 0 else ~i, set()).add(code)
                for p in arcs[i if i >= 0 else ~i]:
                    x, y = proj(p)
                    s = sums.setdefault(code, [0.0, 0.0, 0])
                    s[0] += x; s[1] += y; s[2] += 1

    # An arc is a region border if it is used by one region only on the
    # outside edge, or by two different regions.
    border_counts = {}
    for g in counties:
        for ring in rings(g):
            for i in ring:
                j = i if i >= 0 else ~i
                border_counts[j] = border_counts.get(j, 0) + 1
    borders = []
    for j, owners in arc_owners.items():
        if len(owners) > 1 or border_counts[j] == 1:
            borders.append("M" + "L".join("%.1f,%.1f" % proj(p) for p in arcs[j]))

    data = {
        "viewBox": "0 0 %d %d" % (round(W), round(H)),
        "regions": {c: "".join(v) for c, v in paths.items()},
        "borders": "".join(borders),
        "labels": {c: [round(s[0] / s[2], 1), round(s[1] / s[2], 1)] for c, s in sums.items()},
        "source": "U.S. Census Bureau county boundaries (via us-atlas 3.0.1); "
                  "regions from Texas DSHS county table",
    }
    sys.stdout.write("/* Generated by tools/build_texas_map.py. Do not edit by hand. */\n")
    sys.stdout.write("window.STEADY_TEXAS_MAP = " + json.dumps(data, separators=(",", ":")) + ";\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
